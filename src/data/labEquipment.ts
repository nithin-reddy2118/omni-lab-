export function getInstrumentById(id: string): LabInstrument | undefined {
  const resolved = LEGACY_INSTRUMENT_ALIASES[id] ?? id;
  return (
    LAB_INSTRUMENTS.find((item) => item.id === id) ??
    LAB_INSTRUMENTS.find((item) => item.id === resolved)
  );
}

