export function getChemicalById(id: string): ChemicalSubstance | undefined {
  return CHEMISTRY_CHEMICAL_VAULT.find((c) => c.id === id);
}

export function searchChemicals(
  query: string,
  category: ChemicalCategory | 'All' = 'All'
): ChemicalSubstance[] {
  const q = query.trim().toLowerCase();
  return CHEMISTRY_CHEMICAL_VAULT.filter((chem) => {
    const catOk = category === 'All' || chem.category === category;
    if (!catOk) return false;
    if (!q) return true;
    return (
      chem.name.toLowerCase().includes(q) ||
      chem.commonName.toLowerCase().includes(q) ||
      chem.iupacName.toLowerCase().includes(q) ||
      chem.formula.toLowerCase().includes(q) ||
      chem.symbol.toLowerCase().includes(q) ||
      chem.category.toLowerCase().includes(q) ||
      chem.educationalApplications.some((app) => app.toLowerCase().includes(q))
    );
  });
}
